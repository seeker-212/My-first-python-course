#----------------------------What is dictionary---------------------------------
# In Python, a dictionary is a built-in data structure that stores data in key-value pairs. 
# You can think of it like a real-world dictionary: you look up a "key" (the word) to find 
# its associated "value" (the definition).


dictionary = {"name": "Henry", "age": "25"}

for thing in dictionary:
    print(thing)
    print(dictionary[thing])